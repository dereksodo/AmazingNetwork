"""Write the ER diagrams in docs/diagrams/ from the models. Run: python -m scripts.export_erd"""

import importlib
from pathlib import Path

from sqlalchemy import Table

from app.db import Base

TARGET = Path(__file__).resolve().parents[2] / "docs" / "diagrams"
PARTS = {
    "people": "people and communities",
    "content": "published content",
    "collaboration": "drafts",
    "messaging": "direct messages",
    "moderation": "moderation, notifications and audit",
}


def entity(table: Table) -> str:
    """One entity with its columns and keys."""
    unique = {c.name for c in table.columns if c.unique}
    lines = []
    for column in table.columns:
        keys = [
            key
            for key, on in (
                ("PK", column.primary_key),
                ("FK", bool(column.foreign_keys)),
                ("UK", column.name in unique),
            )
            if on
        ]
        null = ' "nullable"' if column.nullable else ""
        kind = type(column.type).__name__.lower().replace("largebinary", "blob")
        lines.append(f"    {kind} {column.name} {','.join(keys)}{null}".rstrip())
    body = "\n".join(lines)
    return f"  {table.name.upper()} {{\n{body}\n  }}"


def relations(table: Table) -> list[str]:
    """One line per foreign key."""
    result = []
    for column in table.columns:
        for key in column.foreign_keys:
            parent = "|o" if column.nullable else "||"
            single = column.unique or (column.primary_key and len(table.primary_key) == 1)
            child = "o|" if single else "o{"
            result.append(
                f"  {key.column.table.name.upper()} {parent}--{child} {table.name.upper()} : {column.name}"
            )
    return result


def render(module: str, title: str) -> str:
    """Diagram of the tables defined in one models module."""
    name = f"app.models.{module}"
    importlib.import_module(name)
    tables = [m.local_table for m in Base.registry.mappers if m.class_.__module__ == name]
    tables.sort(key=lambda t: t.name)
    lines = [f"%% ER diagram: {title}. Generated by backend/scripts/export_erd.py", "erDiagram"]
    lines += [line for table in tables for line in relations(table)]
    lines += [entity(table) for table in tables]
    return "\n".join(lines) + "\n"


def main() -> None:
    """Write one file per models module."""
    for module, title in PARTS.items():
        (TARGET / f"erd-{module}.mmd").write_text(render(module, title))


if __name__ == "__main__":
    main()
